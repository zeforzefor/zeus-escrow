import { readFileSync, writeFileSync } from 'node:fs'

const artifactPath = 'contracts/out/ZeusEscrow.sol/ZeusEscrow.json'
const outPath = 'src/escrow/bytecode.ts'

const artifact = JSON.parse(readFileSync(artifactPath, 'utf8')) as { bytecode?: { object?: string } }
const object = artifact.bytecode?.object
if (!object || !/^0x[0-9a-fA-F]+$/.test(object)) {
  throw new Error(`No creation bytecode in ${artifactPath}. Run "bun run contracts:build" first.`)
}

writeFileSync(
  outPath,
  `// Generated by scripts/sync-bytecode.ts from the compiled ZeusEscrow artifact. Do not edit.\n` +
    `export const ZEUS_ESCROW_BYTECODE = '${object}' as const\n`,
)
console.log(`Wrote ${outPath} (${(object.length - 2) / 2} bytes)`)
